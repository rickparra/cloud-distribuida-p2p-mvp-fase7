CREATE OR REPLACE PROCEDURE F6POC_ALLOCATE (
    P_JOB_CODE IN VARCHAR2,
    P_NODE_CODE IN VARCHAR2
) AS
    V_JOB_ID F6POC_JOBS.JOB_ID%TYPE;
    V_VCPU F6POC_JOBS.VCPU_REQ%TYPE;
    V_RATE F6POC_NODES.PRICE_PER_VCPU_HOUR%TYPE;
BEGIN
    SELECT JOB_ID, VCPU_REQ INTO V_JOB_ID, V_VCPU
      FROM F6POC_JOBS WHERE JOB_CODE = P_JOB_CODE AND STATUS = 'OPEN'
      FOR UPDATE;
    SELECT PRICE_PER_VCPU_HOUR INTO V_RATE
      FROM F6POC_NODES WHERE NODE_CODE = P_NODE_CODE;
    INSERT INTO F6POC_LEASES (JOB_ID, NODE_CODE, TOTAL_PRICE_BRL, STATUS)
    VALUES (V_JOB_ID, P_NODE_CODE, 0, 'AUTHORIZED');
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20010, 'Carga aberta ou no informado nao encontrado.');
END;
/
