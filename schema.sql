-- @statement
CREATE OR REPLACE TRIGGER TRG_F6POC_LEASE_AUDIT
AFTER INSERT OR UPDATE OF STATUS ON F6POC_LEASES
FOR EACH ROW
DECLARE
    V_SEQ NUMBER(6);
    V_PREV VARCHAR2(64);
    V_KIND VARCHAR2(32);
    V_DETAILS VARCHAR2(1000);
    V_CANONICAL VARCHAR2(2000);
    V_HASH VARCHAR2(64);
    V_VCPU F6POC_JOBS.VCPU_REQ%TYPE;
BEGIN
    IF INSERTING THEN
        UPDATE F6POC_JOBS SET STATUS = 'ALLOCATED' WHERE JOB_ID = :NEW.JOB_ID;
        SELECT VCPU_REQ INTO V_VCPU FROM F6POC_JOBS WHERE JOB_ID = :NEW.JOB_ID;
        UPDATE F6POC_NODES SET VCPU_RESERVED = VCPU_RESERVED + V_VCPU WHERE NODE_CODE = :NEW.NODE_CODE;
        V_KIND := 'LEASE_AUTHORIZED';
        V_DETAILS := 'node=' || :NEW.NODE_CODE || ';price=' || TO_CHAR(:NEW.TOTAL_PRICE_BRL, 'FM999999990D00', 'NLS_NUMERIC_CHARACTERS=.,');
    ELSIF UPDATING AND :OLD.STATUS = 'AUTHORIZED' AND :NEW.STATUS IN ('COMPLETED','FAILED') THEN
        UPDATE F6POC_JOBS SET STATUS = :NEW.STATUS WHERE JOB_ID = :NEW.JOB_ID;
        SELECT VCPU_REQ INTO V_VCPU FROM F6POC_JOBS WHERE JOB_ID = :NEW.JOB_ID;
        UPDATE F6POC_NODES SET VCPU_RESERVED = VCPU_RESERVED - V_VCPU WHERE NODE_CODE = :NEW.NODE_CODE;
        V_KIND := CASE WHEN :NEW.STATUS = 'COMPLETED' THEN 'EXECUTION_COMPLETED' ELSE 'EXECUTION_FAILED' END;
        V_DETAILS := 'lease=' || :NEW.LEASE_ID;
    ELSE
        IF UPDATING AND :NEW.STATUS <> :OLD.STATUS THEN
            RAISE_APPLICATION_ERROR(-20018, 'LEASE_TERMINAL');
        END IF;
        RETURN;
    END IF;

    SELECT NVL(MAX(EVENT_SEQ), 0),
           NVL(MAX(EVENT_HASH) KEEP (DENSE_RANK LAST ORDER BY EVENT_SEQ), '-')
      INTO V_SEQ, V_PREV FROM F6POC_AUDIT_EVENTS WHERE LEASE_ID = :NEW.LEASE_ID;
    V_SEQ := V_SEQ + 1;
    V_CANONICAL := :NEW.LEASE_ID || '|' || V_SEQ || '|' || V_KIND || '|ORACLE_TRIGGER|' || V_DETAILS || '|' || V_PREV;
    SELECT RAWTOHEX(STANDARD_HASH(V_CANONICAL, 'SHA256')) INTO V_HASH FROM DUAL;
    INSERT INTO F6POC_AUDIT_EVENTS
        (LEASE_ID, EVENT_SEQ, EVENT_TYPE, ACTOR, DETAILS, PREVIOUS_HASH, EVENT_HASH)
    VALUES
        (:NEW.LEASE_ID, V_SEQ, V_KIND, 'ORACLE_TRIGGER', V_DETAILS, V_PREV, V_HASH);
END;
