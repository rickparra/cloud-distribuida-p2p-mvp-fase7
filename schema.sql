CREATE OR REPLACE TRIGGER TRG_F6POC_LEASE_GUARD
BEFORE INSERT ON F6POC_LEASES
FOR EACH ROW
DECLARE
    V_CLASS F6POC_JOBS.DATA_CLASSIFICATION%TYPE;
    V_VCPU F6POC_JOBS.VCPU_REQ%TYPE;
    V_MAX F6POC_JOBS.MAX_PRICE_BRL%TYPE;
    V_JOB_STATUS F6POC_JOBS.STATUS%TYPE;
    V_COUNTRY F6POC_NODES.COUNTRY_CODE%TYPE;
    V_TEE F6POC_NODES.TEE_ENABLED%TYPE;
    V_PERSIST F6POC_NODES.LOCAL_PERSISTENCE%TYPE;
    V_APPROVED F6POC_NODES.APPROVED%TYPE;
    V_CAPACITY F6POC_NODES.VCPU_CAPACITY%TYPE;
    V_RESERVED F6POC_NODES.VCPU_RESERVED%TYPE;
    V_RATE F6POC_NODES.PRICE_PER_VCPU_HOUR%TYPE;
    V_TOTAL NUMBER;
    V_PERSONAL NUMBER(1);
BEGIN
    SELECT DATA_CLASSIFICATION, VCPU_REQ, MAX_PRICE_BRL, STATUS
      INTO V_CLASS, V_VCPU, V_MAX, V_JOB_STATUS
      FROM F6POC_JOBS WHERE JOB_ID = :NEW.JOB_ID;
    SELECT COUNTRY_CODE, TEE_ENABLED, LOCAL_PERSISTENCE, APPROVED,
           VCPU_CAPACITY, VCPU_RESERVED, PRICE_PER_VCPU_HOUR
      INTO V_COUNTRY, V_TEE, V_PERSIST, V_APPROVED, V_CAPACITY, V_RESERVED, V_RATE
      FROM F6POC_NODES WHERE NODE_CODE = :NEW.NODE_CODE FOR UPDATE;

    IF V_JOB_STATUS <> 'OPEN' THEN
        RAISE_APPLICATION_ERROR(-20011, 'CARGA_NAO_ABERTA');
    ELSIF V_APPROVED <> 1 THEN
        RAISE_APPLICATION_ERROR(-20012, 'OPERADOR_NAO_HOMOLOGADO');
    ELSIF V_PERSIST <> 0 THEN
        RAISE_APPLICATION_ERROR(-20013, 'NO_COM_PERSISTENCIA_LOCAL');
    ELSIF (V_CAPACITY - V_RESERVED) < V_VCPU THEN
        RAISE_APPLICATION_ERROR(-20014, 'CAPACIDADE_INSUFICIENTE');
    END IF;

    V_PERSONAL := CASE WHEN V_CLASS IN ('PESSOAL','PESSOAL_SENSIVEL') THEN 1 ELSE 0 END;
    IF V_PERSONAL = 1 AND V_COUNTRY <> 'BR' THEN
        RAISE_APPLICATION_ERROR(-20015, 'NO_FORA_DO_BRASIL');
    ELSIF V_PERSONAL = 1 AND V_TEE <> 1 THEN
        RAISE_APPLICATION_ERROR(-20016, 'NO_SEM_EXECUCAO_CONFIDENCIAL');
    END IF;

    V_TOTAL := ROUND(V_VCPU * V_RATE, 2);
    IF V_TOTAL > V_MAX THEN
        RAISE_APPLICATION_ERROR(-20017, 'TETO_DE_PRECO_EXCEDIDO');
    END IF;
    :NEW.TOTAL_PRICE_BRL := V_TOTAL;
END;
/
